export type Messages = typeof MESSAGES

export function formatClock(date: Date): string {
  return new Intl.DateTimeFormat("en-GB", {
    timeZone: TIME_ZONE,
    hour: "2-digit",
    minute: "2-digit",
    second: "2-digit",
    hourCycle: "h23",
  }).format(date)
}

export function formatStamp(value: string): string {
  if (!value) return ""
  const date = new Date(value)
  if (Number.isNaN(date.getTime())) return ""
  return new Intl.DateTimeFormat("en-GB", {
    timeZone: TIME_ZONE,
    hour: "2-digit",
    minute: "2-digit",
    hourCycle: "h23",
    day: "numeric",
    month: "short",
  }).format(date)
}

export function bandWord(band: "free" | "slow" | "congested" | "unknown", m: Messages): string {
  switch (band) {
    case "free":
      return m.good
    case "slow":
      return m.average
    case "congested":
      return m.bad
    case "unknown":
      return m.noReading
    default: {
      const exhaustive: never = band
      return exhaustive
    }
  }
}
